export const cases = [];
function group(family, subtopic, band, text) {
  text.trim().split('\n').forEach((line, index) => {
    const [q, correct, a, b, c, fact] = line.trim().split('|');
    if (!fact || !q.endsWith('？')) throw Error(`${family}/${index}: incomplete editorial row`);
    cases.push({family, subtopic, band, index, q, options:[correct,a,b,c], fact});
  });
}

